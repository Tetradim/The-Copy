def read(rel: str) -> str:
    path = root / rel
    if not path.exists():
        failures.append(f"Missing file: {rel}")
        return ""
    return path.read_text(encoding="utf-8")


def assert_contains(name: str, text: str, needle: str) -> None:
    if needle not in text:
        failures.append(f"{name} should contain {needle!r}.")


def assert_not_contains(name: str, text: str, needle: str) -> None:
    if needle in text:
        failures.append(f"{name} should not contain {needle!r}.")


def assert_match(name: str, text: str, pattern: str) -> None:
    if not re.search(pattern, text, flags=re.S):
        failures.append(f"{name} should match /{pattern}/.")

